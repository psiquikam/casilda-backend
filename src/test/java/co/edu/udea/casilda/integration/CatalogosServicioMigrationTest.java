package co.edu.udea.casilda.integration;

import co.edu.udea.casilda.model.entity.GrupoProfesional;
import co.edu.udea.casilda.model.entity.TipoServicio;
import org.hibernate.SessionFactory;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.registry.StandardServiceRegistry;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

@Testcontainers
class CatalogosServicioMigrationTest {
    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    private Connection connection() throws SQLException {
        return DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
    }

    @BeforeEach
    void crearCatalogosAnteriores() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.execute("""
                    DROP TABLE IF EXISTS historico, grupoprofesional, tiposervicio CASCADE;
                    CREATE TABLE tiposervicio (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre text NOT NULL, activo boolean NOT NULL DEFAULT true);
                    CREATE TABLE grupoprofesional (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre text NOT NULL, activo boolean NOT NULL DEFAULT true);
                    CREATE TABLE historico (idgrupo integer REFERENCES grupoprofesional(id),
                        idservicio integer REFERENCES tiposervicio(id));
                    INSERT INTO tiposervicio (id, nombre) VALUES (1, 'Psicología'), (5, 'Atención APH'), (6, 'Otro');
                    INSERT INTO grupoprofesional (id, nombre) VALUES (1, 'Anterior'), (9, 'Otro');
                    INSERT INTO historico VALUES (1, 5);
                    """);
        }
        StandardServiceRegistry registry = new StandardServiceRegistryBuilder()
                .applySetting("hibernate.connection.url", POSTGRES.getJdbcUrl())
                .applySetting("hibernate.connection.username", POSTGRES.getUsername())
                .applySetting("hibernate.connection.password", POSTGRES.getPassword())
                .applySetting("hibernate.connection.driver_class", "org.postgresql.Driver")
                .applySetting("hibernate.hbm2ddl.auto", "update")
                .build();
        try (SessionFactory ignored = new MetadataSources(registry)
                .addAnnotatedClass(TipoServicio.class)
                .addAnnotatedClass(GrupoProfesional.class)
                .buildMetadata().buildSessionFactory()) {
            // Hibernate performs the schema update when the session factory starts.
        } finally {
            StandardServiceRegistryBuilder.destroy(registry);
        }
    }

    @Test
    void actualizaCatalogosYEsIdempotente() throws Exception {
        String migration = Files.readString(Path.of("database/update_catalogos_servicio_grupo.sql"));
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            assertEquals(List.of("YES"), rows(statement, "SELECT is_nullable FROM information_schema.columns "
                    + "WHERE table_name = 'grupoprofesional' AND column_name = 'idtiposervicio'"));
            statement.execute(migration);
            statement.execute(migration);
            assertEquals(List.of("NO"), rows(statement, "SELECT is_nullable FROM information_schema.columns "
                    + "WHERE table_name = 'grupoprofesional' AND column_name = 'idtiposervicio'"));
            assertEquals(List.of("1:Jurídico", "2:Dupla Psicojurídica", "3:Psicología",
                    "4:Psicoorientación", "5:Trabajo Social"),
                    rows(statement, "SELECT id || ':' || nombre FROM tiposervicio ORDER BY id"));
            assertEquals(List.of("1:Dupla N° 1:2", "2:Dupla N° 2:2", "3:Abogada N° 1:1",
                    "4:Abogada N° 2:1", "5:Psicóloga N° 1:3", "6:Psicóloga N° 2:3",
                    "7:Psicoorientadora:4", "8:Trabajadora social:5"),
                    rows(statement, "SELECT id || ':' || nombre || ':' || idtiposervicio FROM grupoprofesional ORDER BY id"));
            assertEquals(List.of("1:5"), rows(statement, "SELECT idgrupo || ':' || idservicio FROM historico"));
            assertEquals(List.of("9"), rows(statement,
                    "INSERT INTO grupoprofesional (nombre, idtiposervicio) VALUES ('Nuevo', 1) RETURNING id::text"));
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO grupoprofesional (nombre, idtiposervicio) VALUES ('Inválido', 999)"));
        }
    }

    @Test
    void revierteCuandoUnIdAdicionalTieneReferencias() throws Exception {
        String migration = Files.readString(Path.of("database/update_catalogos_servicio_grupo.sql"));
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.execute("INSERT INTO historico VALUES (9, 6)");
            assertThrows(SQLException.class, () -> statement.execute(migration));
            statement.execute("ROLLBACK");
            assertEquals(List.of("1:Psicología", "5:Atención APH", "6:Otro"),
                    rows(statement, "SELECT id || ':' || nombre FROM tiposervicio ORDER BY id"));
            assertEquals(List.of("1:Anterior", "9:Otro"),
                    rows(statement, "SELECT id || ':' || nombre FROM grupoprofesional ORDER BY id"));
            assertEquals(List.of("YES"), rows(statement, "SELECT is_nullable FROM information_schema.columns "
                    + "WHERE table_name = 'grupoprofesional' AND column_name = 'idtiposervicio'"));
        }
    }

    private List<String> rows(Statement statement, String sql) throws SQLException {
        List<String> result = new ArrayList<>();
        try (ResultSet rs = statement.executeQuery(sql)) {
            while (rs.next()) {
                result.add(rs.getString(1));
            }
        }
        return result;
    }
}
