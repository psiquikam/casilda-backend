CREATE TABLE IF NOT EXISTS auditoriarecursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    idusuario BIGINT,
    usuario VARCHAR(255) NOT NULL,
    accion VARCHAR(40) NOT NULL,
    recurso VARCHAR(40) NOT NULL,
    idrecurso VARCHAR(100),
    tablafectada VARCHAR(100) NOT NULL,
    idregistro VARCHAR(100),
    campos TEXT[] NOT NULL DEFAULT '{}',
    endpoint VARCHAR(255) NOT NULL,
    idoperacion UUID NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoriarecursos_recurso_fecha
    ON auditoriarecursos (recurso, idrecurso, fecha DESC);

CREATE INDEX IF NOT EXISTS idx_auditoriarecursos_usuario_fecha
    ON auditoriarecursos (idusuario, fecha DESC);
