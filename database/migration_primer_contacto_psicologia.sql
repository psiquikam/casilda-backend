-- Base de persistencia del primer contacto de Línea Alma.
-- Ejecutar después de crear las tablas de APH, usuario, persona y caso.
-- Es obligatorio ejecutar este script antes de habilitar el backend con consultas
-- de casos de Psicología (bandeja, novedades, notificaciones y consulta previa APH).
-- Requiere que las tablas de permisos ya existan.
-- Reejecutar antes de desplegar recontactos: agrega su tabla y permisos de forma idempotente.

CREATE TABLE IF NOT EXISTS consecutivocasopsicologia (
    anio INTEGER PRIMARY KEY,
    ultimo INTEGER NOT NULL CHECK (ultimo BETWEEN 1 AND 999999)
);

CREATE TABLE IF NOT EXISTS casopsicologia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(16) NOT NULL UNIQUE,
    version INTEGER NOT NULL CHECK (version > 0),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('ABIERTO', 'ACTIVO', 'EN_CIERRE', 'CERRADO')),
    prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('ALTA', 'MEDIA', 'BAJA')),
    idtipoidentificacion INTEGER NOT NULL REFERENCES tipoidentificacion(id),
    numerodocumento VARCHAR(50) NOT NULL,
    idpersona BIGINT REFERENCES persona(id),
    idprofesional BIGINT NOT NULL REFERENCES usuario(id),
    triajeaph VARCHAR(10) CHECK (triajeaph IN ('ALTO', 'MEDIO', 'BAJO')),
    fechaapertura TIMESTAMPTZ NOT NULL,
    fechaactualizacion TIMESTAMPTZ NOT NULL,
    proximocontrol TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_casopsicologia_persona_estado
    ON casopsicologia (idtipoidentificacion, numerodocumento, estado);
CREATE INDEX IF NOT EXISTS idx_casopsicologia_documento_normalizado_estado
    ON casopsicologia (idtipoidentificacion, upper(numerodocumento), estado);

-- Una atención puede vincularse a un caso propio o a un caso existente, nunca a ambos.
-- El contenido clínico se mantiene separado de los datos visibles para APH.
CREATE TABLE IF NOT EXISTS primercontactopsicologia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idatencion BIGINT NOT NULL UNIQUE REFERENCES atencionalmaaph(id),
    idcasopsicologia BIGINT REFERENCES casopsicologia(id),
    idcaso BIGINT REFERENCES caso(id),
    idusuario BIGINT NOT NULL REFERENCES usuario(id),
    fecharegistro TIMESTAMPTZ NOT NULL,
    datos JSONB NOT NULL CHECK (jsonb_typeof(datos) = 'object'),
    CONSTRAINT ck_primercontacto_caso CHECK ((idcasopsicologia IS NULL) <> (idcaso IS NULL))
);

CREATE INDEX IF NOT EXISTS idx_primercontacto_casopsicologia
    ON primercontactopsicologia (idcasopsicologia);
CREATE INDEX IF NOT EXISTS idx_primercontacto_caso
    ON primercontactopsicologia (idcaso);

CREATE TABLE IF NOT EXISTS eventocasopsicologia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcasopsicologia BIGINT NOT NULL REFERENCES casopsicologia(id),
    idusuario BIGINT NOT NULL REFERENCES usuario(id),
    accion VARCHAR(30) NOT NULL,
    detalle VARCHAR(500) NOT NULL,
    fecha TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_eventocasopsicologia_historial
    ON eventocasopsicologia (idcasopsicologia, fecha, id);

-- La resolución es independiente del primer contacto: no inventa un contacto clínico.
CREATE TABLE IF NOT EXISTS resolucionrecontactopsicologia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idatencion BIGINT NOT NULL UNIQUE REFERENCES atencionalmaaph(id),
    idcasopsicologia BIGINT REFERENCES casopsicologia(id),
    idcaso BIGINT REFERENCES caso(id),
    idusuario BIGINT NOT NULL REFERENCES usuario(id),
    decision VARCHAR(30) NOT NULL CHECK (decision IN ('CASO_NUEVO','VINCULAR_A_CASO','CONTENCION_PUNTUAL')),
    nota VARCHAR(1000) NOT NULL,
    reabrio BOOLEAN NOT NULL DEFAULT false,
    fechacierreanterior TIMESTAMPTZ,
    fecha TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_resolucionrecontacto_caso CHECK (
        (decision = 'CASO_NUEVO' AND idcasopsicologia IS NULL AND idcaso IS NULL AND NOT reabrio)
        OR (decision <> 'CASO_NUEVO' AND ((idcasopsicologia IS NULL) <> (idcaso IS NULL)))
    )
);

CREATE INDEX IF NOT EXISTS idx_resolucionrecontacto_casopsicologia
    ON resolucionrecontactopsicologia (idcasopsicologia);
CREATE INDEX IF NOT EXISTS idx_resolucionrecontacto_caso
    ON resolucionrecontactopsicologia (idcaso);

INSERT INTO endpoint (path, http_method, activo, publico)
VALUES ('/alma/psicologia/novedades/{idAtencion}/primer-contacto', 'POST', true, false),
       ('/alma/psicologia/recontactos', 'GET', true, false),
       ('/alma/psicologia/recontactos/{idAtencion}/resolucion', 'GET', true, false),
       ('/alma/psicologia/recontactos/{idAtencion}/resolucion', 'POST', true, false)
ON CONFLICT (path, http_method) DO UPDATE SET activo=true, publico=false;

INSERT INTO endpointrole (idendpoint, idrol)
SELECT e.id, r.id FROM endpoint e
JOIN rol r ON r.codigo IN ('ADMIN', 'COORDINADOR', 'PROFESIONAL')
WHERE (e.path='/alma/psicologia/novedades/{idAtencion}/primer-contacto' AND e.http_method='POST')
   OR (e.path='/alma/psicologia/recontactos/{idAtencion}/resolucion' AND e.http_method='POST')
   OR (e.path='/alma/psicologia/recontactos/{idAtencion}/resolucion' AND e.http_method='GET')
   OR (e.path='/alma/psicologia/recontactos' AND e.http_method='GET')
ON CONFLICT (idendpoint, idrol) DO NOTHING;

INSERT INTO endpointrole (idendpoint, idrol)
SELECT e.id, r.id FROM endpoint e JOIN rol r ON r.codigo='REVISOR'
WHERE e.path IN ('/alma/psicologia/recontactos', '/alma/psicologia/recontactos/{idAtencion}/resolucion')
  AND e.http_method='GET'
ON CONFLICT (idendpoint, idrol) DO NOTHING;
