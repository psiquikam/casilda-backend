-- Persistir la asignación de Psicología separada de la asignación del técnico APH.
ALTER TABLE atencionalmaaph
    ADD COLUMN IF NOT EXISTS idusuariotomadorpsicologia BIGINT REFERENCES usuario(id);
ALTER TABLE atencionalmaaph
    ADD COLUMN IF NOT EXISTS fechatomapsicologia TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS intentocontactopsicologia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idatencionalmaaph BIGINT NOT NULL REFERENCES atencionalmaaph(id),
    numero INTEGER NOT NULL,
    protocolo VARCHAR(30) NOT NULL,
    fechahora TIMESTAMP WITH TIME ZONE NOT NULL,
    resultado VARCHAR(40) NOT NULL,
    nota VARCHAR(2000) NOT NULL,
    justificacion VARCHAR(2000),
    idusuario BIGINT NOT NULL REFERENCES usuario(id),
    CONSTRAINT uk_intentopsicologia_atencion_numero UNIQUE (idatencionalmaaph, numero)
);

